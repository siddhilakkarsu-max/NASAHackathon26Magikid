// Live integration: the existing assistant and green Play button, never a replacement setup.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.MARSWALK_TEST_URL || 'http://127.0.0.1:8012';
const out=path.resolve(process.env.MARSWALK_AUDIT_DIR || 'game_state/planner-flow-audit');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1280,height:900},reducedMotion:'reduce'});
await context.addInitScript(()=>{try{localStorage.setItem('mapManualSeen','1');}catch(_){/* opaque third-party frames have no local storage */}});
const errors=[],checks=[],apiFailures=[];let game;
context.on('page',p=>{p.on('pageerror',e=>errors.push(e.message));p.on('response',r=>{if(r.status()>=400&&r.url().includes('/api/game/'))apiFailures.push({url:r.url(),status:r.status()});});});
const pass=name=>{checks.push(name);console.log('PASS '+name);};
try {
 const page=await context.newPage();page.setDefaultTimeout(60000);
 await page.goto(base+'/',{waitUntil:'domcontentloaded'});
 await page.locator('#startExploring').click();
 await page.waitForFunction(()=>window.marsAssistant&&document.getElementById('region').options.length>2);
 await page.locator('#regionsButton').click();await page.selectOption('#region','jezero');await page.locator('#drawerClose').click();
 await page.getByRole('button',{name:'Assistant',exact:true}).click();
 await page.getByPlaceholder('Reply or ask anything…').fill('find clay where water once flowed');
 await page.getByPlaceholder('Reply or ask anything…').press('Enter');
 await page.getByRole('button',{name:'Midday (12:00)',exact:true}).click();
 await page.getByRole('button',{name:'Pressurized rover',exact:true}).click();
 await page.locator('#playFab').waitFor({state:'visible',timeout:180000});
 const handoff=await page.evaluate(()=>window.MarswalkGameLaunch.buildPayload());
 assert.equal(handoff.request.local_hour,12);assert.equal(handoff.request.vehicle,'buggy');
 assert.equal(handoff.mission.settings.goal,'find clay where water once flowed');
 const server=await (await context.request.get(base+'/api/game/plans/'+handoff.mission.id)).json();
 assert.equal(server.available,true,server.reason);
 assert.deepEqual(server.plan.candidates[handoff.selected].route.points,handoff.mission.candidates[handoff.selected].route.points);
 pass('Real assistant goal → midday → pressurized rover generates and saves the exact mission');
 const popup=page.waitForEvent('popup');await page.locator('#playFab').click();game=await popup;
 await game.waitForFunction(()=>window.__MW?.getSnapshot().screen==='brief');
 const initial=await game.evaluate(()=>({snap:__MW.getSnapshot(),hour:__MW.state.N.localHour,route:__MW.state.N.cands[__MW.state.ci].route.points}));
 assert.equal(initial.snap.mission.id,handoff.mission.id);assert.equal(initial.hour,12);assert.equal(initial.snap.mission.vehicle,'buggy');
 assert.deepEqual(initial.route.map(({lat,lon})=>({lat,lon})),handoff.mission.candidates[handoff.selected].route.points.map(({lat,lon})=>({lat,lon})));
 assert.equal(await game.locator('#brief .briefOptions > details[open]').count(),0);
 await game.screenshot({path:path.join(out,'briefing.png')});
 await game.locator('#bLaunch').click();
 await game.waitForFunction(()=>__MW.getSnapshot().screen==='play'&&__MW.getSnapshot().paused);
 const ready=await game.evaluate(()=>__MW.getSnapshot());await game.waitForTimeout(500);
 assert.equal((await game.evaluate(()=>__MW.getSnapshot())).t,ready.t,'ready state must not drain resources');
 assert.ok(ready.tools.length>0&&ready.spots>0,'science tools and sampling locations survive');
 assert.ok(await game.evaluate(()=>__MW.hazards().shelters.length>0),'original shelters survive');
 assert.equal(await game.locator('#mini').isVisible(),true);
 pass('Green Play preserves selected mission; compact briefing enters the original game ready to drive');
 await game.locator('#btnDrive').click();
 await game.waitForFunction(()=>!__MW.getSnapshot().paused);
 assert.equal(await game.evaluate(()=>window.MarswalkRouteMap.isOpen()),false);
 await game.keyboard.down('w');
 try{await game.waitForFunction(({x,y})=>{const s=__MW.getSnapshot();return Math.hypot(s.x-x,s.y-y)>1;},{x:ready.x,y:ready.y},{timeout:15000});}
 finally{await game.keyboard.up('w');}
 const driven=await game.evaluate(()=>__MW.getSnapshot());
 assert.ok(Math.hypot(driven.x-ready.x,driven.y-ready.y)>1,'W drives the original rover');
 assert.ok(driven.t>ready.t);assert.equal(driven.nan,false);
 await game.screenshot({path:path.join(out,'driving.png')});
 pass('Start driving starts driving directly, with the original vehicle and corner minimap');
 await game.locator('#btnLeaderboard').click();await game.locator('#gameBoard').waitFor({state:'visible'});
 await game.locator('#boardRoutes').click();await game.waitForFunction(()=>!document.getElementById('routeBoardContent').textContent.includes('Loading'));
 assert.match(await game.locator('#routeBoardContent').innerText(),/Simulated|simulated|No completed/);
 await game.locator('#boardClose').click();
 await game.locator('#btnEditMap').click();await game.locator('#routeMapDialog').waitFor({state:'visible'});
 assert.equal((await game.evaluate(()=>__MW.getSnapshot())).paused,true);
 const box=await game.locator('#routeMapDialog').boundingBox();assert.ok(box.width<1100&&box.height<810,'editor is a contained popup');
 assert.equal(await game.locator('#routeMapDialog input[type=number]').count(),0);
 await game.waitForTimeout(4000);await game.screenshot({path:path.join(out,'satellite-map.png')});
 const state=await game.evaluate(()=>MarswalkRouteMap.snapshot());
 const point=state.route[1],rect=state.rect,cb=await game.locator('#routeMapCanvas').boundingBox();
 const x=cb.x+(point.lon-rect.west)/(rect.east-rect.west)*cb.width,y=cb.y+(rect.north-point.lat)/(rect.north-rect.south)*cb.height;
 await game.mouse.move(x,y);await game.mouse.down();await game.mouse.move(x+3,y+3,{steps:3});await game.mouse.up();
 assert.equal((await game.evaluate(()=>MarswalkRouteMap.snapshot())).dirty,true);
 await game.getByRole('button',{name:'Undo',exact:true}).click();
 assert.deepEqual((await game.evaluate(()=>MarswalkRouteMap.snapshot())).route,state.route);
 await game.locator('#routeMapDialog [data-layer=topography]').click();
 await game.waitForFunction(()=>MarswalkRouteMap.snapshot().terrainLoaded,{},{timeout:90000});
 await game.screenshot({path:path.join(out,'topography-map.png')});
 await game.getByRole('button',{name:'Back to rover',exact:true}).click();
 assert.deepEqual((await game.evaluate(()=>__MW.mapBridge.getContext().C.route.points)).map(({lat,lon})=>({lat,lon})),initial.route.map(({lat,lon})=>({lat,lon})));
 pass('Leaderboard and satellite/topography editor are reachable; drag/undo/cancel preserves the original route');
 await game.locator('#btnEditMap').click();
 const editState=await game.evaluate(()=>MarswalkRouteMap.snapshot()),editBox=await game.locator('#routeMapCanvas').boundingBox();
 const ep=editState.route[1],er=editState.rect;
 const ex=editBox.x+(ep.lon-er.west)/(er.east-er.west)*editBox.width,ey=editBox.y+(er.north-ep.lat)/(er.north-er.south)*editBox.height;
 await game.mouse.move(ex,ey);await game.mouse.down();await game.mouse.move(ex,ey+2,{steps:2});await game.mouse.up();
 await game.getByRole('button',{name:'Use route',exact:true}).click();await game.locator('#routeMapDialog').waitFor({state:'hidden'});
 const edited=await game.evaluate(()=>({snap:__MW.getSnapshot(),context:__MW.mapBridge.getContext().C.route.points}));
 assert.equal(edited.snap.paused,true);assert.equal(edited.snap.t,0);assert.equal(edited.snap.mission.id,handoff.mission.id);
 assert.notDeepEqual(edited.context.map(({lat,lon})=>({lat,lon})),initial.route.map(({lat,lon})=>({lat,lon})));
 const unchanged=await (await context.request.get(base+'/api/game/plans/'+handoff.mission.id)).json();
 assert.deepEqual(unchanged.reference.points,server.reference.points,'route edits cannot rewrite the original AI reference');
 await game.locator('#btnDrive').click();await game.waitForFunction(()=>!__MW.getSnapshot().paused);
 assert.equal(await game.evaluate(()=>MarswalkRouteMap.isOpen()),false);
 pass('Applying a dragged route restarts the original game at A, preserves its reference, and drives directly');
 for(const [width,height] of [[760,900],[390,844]]){
   await game.setViewportSize({width,height});await game.locator('#btnEditMap').click();
   const bounds=await game.locator('#routeMapDialog').boundingBox();assert.ok(bounds.x>=0&&bounds.x+bounds.width<=width+1);
   assert.ok(bounds.y>=0&&bounds.y+bounds.height<=height+1);
   await game.screenshot({path:path.join(out,`map-${width}.png`)});await game.getByRole('button',{name:'Back to rover',exact:true}).click();
   const overflow=await game.evaluate(()=>({page:document.documentElement.scrollWidth>innerWidth,buttons:[...document.querySelectorAll('#hudBtns button')].filter(b=>{const r=b.getBoundingClientRect();return r.x<0||r.right>innerWidth+1;}).length}));
   assert.equal(overflow.page,false);assert.equal(overflow.buttons,0);
 }
 pass('Editor and game controls fit desktop, tablet and phone widths');
 assert.deepEqual(errors,[]);assert.deepEqual(apiFailures,[]);
 await fs.writeFile(path.join(out,'handoff.json'),JSON.stringify(handoff));
} catch(e){if(game)await game.screenshot({path:path.join(out,'failure.png')}).catch(()=>{});throw e;}
finally{await fs.writeFile(path.join(out,'report.json'),JSON.stringify({checks,errors,apiFailures},null,2));await browser.close();}
