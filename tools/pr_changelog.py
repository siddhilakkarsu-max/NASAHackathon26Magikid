"""Write one changelog file per merged pull request into docs/changelog/, straight from git history.

    python tools/pr_changelog.py            # (re)write every PR file + docs/changelog/README.md
    python tools/pr_changelog.py --check    # exit 1 if a merged PR has no changelog file (for reviewers / CI)

For each "Merge pull request #N" commit on main it records: title, author, who merged, date, the PR's commits,
the files it changed, and MERGE CONFLICTS. Conflicts are found by re-running each merge with
`git merge-tree` (git >= 2.38): the PR merge itself and every merge made inside the branch (e.g. pulling main in).
For each conflicted file it says how it was resolved: kept the branch side, kept the main side, or combined both.

A file that already exists is only rewritten between the AUTO markers, so notes written by hand above or below
them survive. Needs a full clone (`git fetch --unshallow` if `git rev-parse --is-shallow-repository` says true).
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "changelog"
BEGIN, END = "<!-- AUTO: generated by tools/pr_changelog.py -->", "<!-- /AUTO -->"


def git(*args, ok=(0,)):
    p = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    if p.returncode not in ok:
        raise RuntimeError(f"git {' '.join(args)}: {p.stderr.strip()}")
    return p.stdout, p.returncode


def merged_prs(ref="origin/main"):
    try:
        git("rev-parse", "--verify", ref)
    except RuntimeError:
        ref = "main"
    out, _ = git("log", ref, "--first-parent", "--merges", "--format=%H%x1f%P%x1f%an%x1f%ad%x1f%B%x1e",
                 "--date=short")
    prs = []
    for rec in out.split("\x1e"):
        if not rec.strip():
            continue
        h, parents, merger, date, body = rec.strip("\n").split("\x1f")
        m = re.match(r"Merge pull request #(\d+) from ([^\s]+)", body)
        if not m:
            continue
        p = parents.split()
        title = next((l.strip() for l in body.splitlines()[1:] if l.strip()), "")
        prs.append(dict(n=int(m.group(1)), branch=m.group(2), sha=h, base=p[0], head=p[1], merger=merger,
                        date=date, title=title))
    return sorted(prs, key=lambda x: x["n"])


def conflicts(p1, p2):
    """Files git can't merge automatically when merging p2 into p1 (re-run with merge-tree)."""
    out, code = git("merge-tree", "--write-tree", "--name-only", "--no-messages", p1, p2, ok=(0, 1))
    if code == 0:
        return []
    lines = out.splitlines()[1:]                      # first line is the tree id
    return sorted({l for l in lines if l.strip()})


def blob(rev, path):
    out, code = git("rev-parse", "--verify", "--quiet", f"{rev}:{path}", ok=(0, 1))
    return out.strip() if code == 0 else None


def resolution(merge, p1, p2, path):
    r, a, b = blob(merge, path), blob(p1, path), blob(p2, path)
    if r is None:
        return "file deleted in the merge"
    if r == a:
        return "kept the first parent's version"
    if r == b:
        return "kept the incoming version"
    return "combined both versions by hand"


def pr_conflicts(pr):
    """[(where, [(file, how)])] for the PR merge and for every merge made inside the PR branch."""
    found = []
    events = [("merging the PR into main", pr["sha"], pr["base"], pr["head"])]
    out, _ = git("log", "--merges", "--format=%H %P%x1f%s", f"{pr['base']}..{pr['head']}")
    for line in out.splitlines():
        shas, subject = line.split("\x1f")
        h, *ps = shas.split()
        if len(ps) == 2:
            events.append((f"branch merge {h[:7]} \"{subject}\"", h, ps[0], ps[1]))
    for where, m, a, b in events:
        files = conflicts(a, b)
        if files:
            found.append((where, [(f, resolution(m, a, b, f)) for f in files]))
    return found


def render(pr):
    commits, _ = git("log", "--no-merges", "--reverse", "--format=- %h %s (%an)", f"{pr['base']}..{pr['head']}")
    files, _ = git("diff", "--stat=100", pr["base"], pr["sha"])
    authors, _ = git("log", "--no-merges", "--format=%an", f"{pr['base']}..{pr['head']}")
    authors = sorted(set(authors.split("\n")) - {""})
    found = pr_conflicts(pr)
    lines = [BEGIN, f"# PR #{pr['n']}: {pr['title'] or pr['branch']}", "",
             f"- Branch: `{pr['branch']}`",
             f"- Authors: {', '.join(authors) or 'unknown'}",
             f"- Merged by {pr['merger']} on {pr['date']} (merge commit `{pr['sha'][:7]}`)", "",
             "## Merge conflicts", ""]
    if not found:
        lines.append("None: git merged every file automatically.")
    for where, items in found:
        lines.append(f"While {where}:" if where.startswith("merging") else f"In {where}:")
        lines += [f"- `{f}`: {how}" for f, how in items]
        lines.append("")
    lines += ["", "## Commits", "", commits.strip() or "- (no commits of its own)", "",
              "## Files changed", "", "```", files.rstrip(), "```", END]
    return "\n".join(lines) + "\n", found


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    prs = merged_prs()
    if "--check" in sys.argv:
        missing = [p["n"] for p in prs if not list(OUT.glob(f"PR-{p['n']:03d}-*.md"))]
        print("missing changelog for PR " + ", ".join(f"#{n}" for n in missing) if missing else "all merged PRs have a changelog")
        sys.exit(1 if missing else 0)
    index = ["# Changelog: one file per merged pull request", "",
             "Written by `python tools/pr_changelog.py` from git history (see the rule in `AGENTS.md`).",
             "Each file lists the PR's commits, the files it changed and any merge conflicts and how they were",
             "resolved. Hand-written notes go outside the AUTO markers and are kept when the file is regenerated.", "",
             "| PR | Title | Branch | Merged | Conflicts |", "|---|---|---|---|---|"]
    for pr in prs:
        text, found = render(pr)
        old = list(OUT.glob(f"PR-{pr['n']:03d}-*.md"))
        path = old[0] if old else OUT / f"PR-{pr['n']:03d}-{slug(pr['branch'].split('/', 1)[-1])}.md"
        if path.exists():
            cur = path.read_text()
            if BEGIN in cur and END in cur:
                text = cur.split(BEGIN)[0] + text.rstrip("\n") + cur.split(END, 1)[1]
        path.write_text(text)
        n_files = sum(len(items) for _, items in found)
        index.append(f"| [#{pr['n']}]({path.name}) | {pr['title'] or '-'} | `{pr['branch']}` | {pr['date']} | "
                     f"{f'{n_files} file(s)' if n_files else 'none'} |")
    (OUT / "README.md").write_text("\n".join(index) + "\n")
    print(f"wrote {len(prs)} PR changelogs to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
